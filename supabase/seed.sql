-- 2. 认知 (Cognition)
--    - 核心关注：提升思维质量与元认知能力
--    - 相关目标示例：建立深度思考习惯、学习批判性思维
--    - 相关行动示例：每日写作反思、阅读+笔记、结构化思考练习

-- 3. 技能 (Skills)
--    - 核心关注：专业能力提升与工具掌握
--    - 相关目标示例：掌握全栈开发、提升产品能力
--    - 相关行动示例：每日编码练习、学习新技术、完成项目实践

-- 4. 财务 (Finance)
--    - 核心关注：收入增长与资产管理
--    - 相关目标示例：建立被动收入、优化支出结构
--    - 相关行动示例：记账复盘、学习投资知识、探索副业

